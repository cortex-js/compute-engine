const parse = (cat) => {
  const out = { A: 0, B: 0, C: 0, D: 0, E: 0 };
  const m = cat.match(/[A-E]\d*/g);
  if (m.length === 1 && m[0].length === 1) { out[m[0]] = 100; return out; }
  for (const p of m) out[p[0]] = +p.slice(1);
  return out;
};
const rows = [];
const push = (file, s, e, cat, conf, name, reason) => {
  const n = e - s + 1;
  const sp = parse(cat);
  const parts = ['A', 'B', 'C', 'D', 'E'].map((k) => Math.round((n * sp[k]) / 100));
  // fix rounding so parts sum to n
  const diff = n - parts.reduce((a, b) => a + b, 0);
  parts[parts.indexOf(Math.max(...parts))] += diff;
  rows.push({ file, s, e, n, cat, conf, name, reason, parts });
};

