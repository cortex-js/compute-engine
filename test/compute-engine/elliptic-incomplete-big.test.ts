/** Digits in which `got` agrees with `expected`, relative to `expected`. */
function agreement(got: Expression, expected: string): number {
  const saved = BigDecimal.precision;
  BigDecimal.precision = 300;
  try {
    const e = new BigDecimal(expected);
    const g = new BigDecimal(got.toString());
    const diff = g.sub(e).abs();
    if (diff.isZero()) return Infinity;
    return -Math.log10(diff.div(e.abs()).toNumber());
  } finally {
    BigDecimal.precision = saved;
  }
}

// BigDecimal.precision is shared by every engine, so an engine whose
// `precision` is set to the value it already has does not restore it after
// another engine ran at another one: each test makes its own engine.
function engineAt(precision: number | 'machine'): ComputeEngine {
  const e = new ComputeEngine();
  e.precision = precision;
  return e;
}

describe('incomplete elliptic integrals at the precision asked', () => {
  for (const [head, args, expected] of rows) {
    for (const precision of [30, 50, 100].filter((p) => expected[p])) {
      test(`${head}(${args.join(', ')}) (N at ${precision} digits)`, () => {
        const ce = engineAt(precision);
        const r = ce.expr([head, ...args.map(num)]).N();
        expect(r.operator).not.toBe(head);
        expect(agreement(r, expected[precision]!)).toBeGreaterThan(
          precision - LOST_WORST
        );
      });
    }

    // A double operand near a singularity is not the decimal one (1 − 1e-20
    // is 1; at 1 − 1e-8 the condition number is 1e8), so those rows are not
    // compared in doubles.
    const nearSingular =
      args.some((a) => /^0\.9{5,}/.test(a)) ||
      args.includes('1.5707963267948966');
    (nearSingular ? test.skip : test)(
      `${head}(${args.join(', ')}) (machine precision, compiled JavaScript)`,
      () => {
        const want = Number(expected['30']);
        const close = (got: number) =>
          expect(Math.abs(got - want) / Math.abs(want)).toBeLessThan(1e-13);
        const machine = engineAt('machine');
        close(machine.expr([head, ...args.map(num)]).N().re);
        const names = args.map((_, i) => `v${i}`);
        const f = compile(machine.box([head, ...names]));
        close(
          f.run!(
            Object.fromEntries(names.map((n, i) => [n, Number(args[i])]))
          ) as number
        );
      }
    );
  }

  for (const [head, args, expected] of exactRows) {
    for (const precision of [30, 50]) {
      test(`${head}(${JSON.stringify(args)}) (exact operands, N at ${precision} digits)`, () => {
        const ce = engineAt(precision);
        const r = ce.expr([head, ...args] as any).N();
        expect(agreement(r, expected[precision]!)).toBeGreaterThan(
          precision - LOST_WORST
        );
      });
    }

    test(`${head}(${JSON.stringify(args)}) stays exact under evaluate()`, () => {
      const ce = engineAt(30);
      const call = ce.expr([head, ...args] as any);
      expect(call.evaluate().operator).toBe(head);
    });
  }

  test('a float operand gives a float with the precision asked, without N()', () => {
    const ce = engineAt(30);
    const r = ce.expr(['EllipticE', num('0.5'), num('0.3')]).evaluate();
    expect(r.isExact).toBe(false);
    const want = rows.find(
      ([head, args]) => head === 'EllipticE' && args.join() === '0.5,0.3'
    )![2]['30'];
    expect(agreement(r, want)).toBeGreaterThan(29);
    expect(r.toString().replace('0.', '').length).toBeGreaterThan(25);
  });

  test('a rational stays a rational under evaluate()', () => {
    const ce = engineAt(30);
    expect(
      ce.expr(['EllipticE', ['Rational', 1, 2], ['Rational', 3, 10]]).evaluate()
        .operator
    ).toBe('EllipticE');
  });

  test('EllipticPi at 1 - n sin²φ < 0 is the Cauchy principal value (#422)', () => {
    // The rows above with n > 1 hold the real part of mpmath's value for n + i0⁺
    // (checked by a principal-value integral to 40 digits); the machine
    // kernel gives the same number.
    const ce = engineAt(30);
    const r = ce.expr(['EllipticPi', 2, num('0.3')]).N();
    expect(r.im).toBe(0);
    expect(r.re).toBeCloseTo(-0.15182298474781241, 14);
  });

  test('a complex value of real operands is the double complex value', () => {
    const ce = engineAt(30);
    const r = ce.expr(['EllipticF', 2, 2]).N();
    // mpmath ellipf(2, 2) = 1.31102877714606 - 1.77073170766946i
    expect(r.re).toBeCloseTo(1.311028777146059, 13);
    expect(r.im).toBeCloseTo(-1.770731707669461, 13);
  });

  test('the poles are infinite', () => {
    const ce = engineAt(30);
    expect(
      ce
        .expr(['EllipticPi', 1, num('0.3')])
        .N()
        .toString()
    ).toBe('+oo');
    expect(
      ce
        .expr(['EllipticPi', num('0.3'), 1])
        .N()
        .toString()
    ).toBe('+oo');
  });
});
