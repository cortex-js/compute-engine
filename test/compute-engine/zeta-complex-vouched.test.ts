// [Re s, Im s] with |Im s| = 1e5 or 1e6
const declined: [string, string][] = [
  ['0.5', '1e5'],
  ['0', '1e5'],
  ['2', '1e5'],
  ['1', '1e5'],
  ['3', '1e5'],
  ['-1', '1e5'],
  ['-5.5', '1e5'],
  ['0.1', '1e5'],
  ['0.5', '1e6'],
  ['0', '1e6'],
  ['2', '1e6'],
  ['1', '1e6'],
  ['3', '1e6'],
  ['-1', '1e6'],
  ['-5.5', '1e6'],
  ['0.1', '1e6'],
];

const relativeError = (
  got: { re: number; im: number },
  re: string,
  im: string
) =>
  Math.hypot(got.re - Number(re), got.im - Number(im)) /
  Math.hypot(Number(re), Number(im));

const s = (re: string, im: string) => ['Complex', { num: re }, { num: im }];

describe('Zeta at a complex s', () => {
  const ce = new ComputeEngine();

  for (const [re, im, zr, zi] of answered) {
    for (const precision of [15, 21, 30]) {
      test(`zeta(${re} + ${im}i) = ${zr} + ${zi}i (N at ${precision} digits)`, () => {
        ce.precision = precision;
        const r = ce.expr(['Zeta', s(re, im)]).N();
        expect(relativeError(r, zr, zi)).toBeLessThan(1.5e-13);
      });
    }

    test(`zeta(${re} + ${im}i) agrees with HurwitzZeta(s, 1)`, () => {
      ce.precision = 21;
      const a = ce.expr(['Zeta', s(re, im)]).N();
      const b = ce.expr(['HurwitzZeta', s(re, im), 1]).N();
      expect(a.re).toBe(b.re);
      expect(a.im).toBe(b.im);
    });
  }

  for (const [re, im] of declined) {
    test(`zeta(${re} + ${im}i) stays unevaluated: the digits cannot be vouched for`, () => {
      ce.precision = 21;
      expect(ce.expr(['Zeta', s(re, im)]).N().operator).toBe('Zeta');
    });
  }

  test('exact operands stay symbolic under evaluate()', () => {
    expect(ce.expr(['Zeta', ['Complex', 1, 2]]).evaluate().operator).toBe(
      'Zeta'
    );
  });

  test('a float operand gives a float without N()', () => {
    ce.precision = 21;
    const call = ce.expr(['Zeta', ['Complex', 0.5, 100.25]]);
    expect(call.evaluate().operator).not.toBe('Zeta');
    expect(call.evaluate().isExact).toBe(false);
    expect(call.evaluate().re).toBe(call.N().re);
  });

  test('the pole, the real axis and a real s are unchanged', () => {
    ce.precision = 21;
    expect(ce.expr(['Zeta', 1]).N().toString()).toBe('~oo');
    expect(ce.expr(['Zeta', 2]).N().re).toBeCloseTo(Math.PI ** 2 / 6, 15);
    expect(ce.expr(['Zeta', -1]).N().re).toBeCloseTo(-1 / 12, 15);
  });
});
