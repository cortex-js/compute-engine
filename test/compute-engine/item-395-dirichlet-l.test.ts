describe('DirichletCharacter (#395)', () => {
  for (const [k, j, row] of characters) {
    test(`DirichletCharacter(${k}, ${j}, n) for n = 1..${k}`, () => {
      row.split(' ').forEach((token, i) => {
        const n = i + 1;
        const got = num(['DirichletCharacter', k, j, n]);
        if (token === '.') {
          expect([k, j, n, got.re, got.im]).toEqual([k, j, n, 0, 0]);
          return;
        }
        const [p, q = '1'] = token.split('/');
        const angle = (2 * Math.PI * Number(p)) / Number(q);
        expect(got.re).toBeCloseTo(Math.cos(angle), 12);
        expect(got.im).toBeCloseTo(Math.sin(angle), 12);
      });
    });
  }

  const exact: [unknown, string][] = [
    [['DirichletCharacter', 5, 1, 2], '1'],
    [['DirichletCharacter', 4, 2, 3], '-1'],
    [['DirichletCharacter', 5, 2, 2], 'i'],
    [['DirichletCharacter', 5, 2, 3], '-i'],
    [['DirichletCharacter', 5, 2, 5], '0'],
    [['DirichletCharacter', 1, 1, 7], '1'],
    [['DirichletCharacter', 3, 2, ['List', 1, 2, 3, 4, 5]], '[1,-1,0,1,-1]'],
    [['DirichletCharacter', 12, 3, ['List', 1, 5, 7, 11]], '[1,1,-1,-1]'],
  ];
  for (const [json, expected] of exact) {
    test(`${JSON.stringify(json)} = ${expected} (exact)`, () => {
      expect(
        ce
          .box(json as never)
          .evaluate()
          .toString()
      ).toBe(expected);
    });
  }

  test('a character mod 7 at a primitive root is a sixth root of unity, exactly e^(2πi/3)', () => {
    expect(ce.box(['DirichletCharacter', 7, 3, 3]).evaluate().toString()).toBe(
      'e^(2/3i * pi)'
    );
  });

  test('parse route', () => {
    expect(
      ce
        .parse('\\operatorname{DirichletCharacter}(5,2,2)')
        .evaluate()
        .toString()
    ).toBe('i');
  });

  test('characters are completely multiplicative: χ(a)χ(b) = χ(ab) mod 45', () => {
    for (let j = 1; j <= 24; j += 5)
      for (const [a, b] of [
        [7, 11],
        [2, 13],
        [4, 17],
        [8, 8],
      ]) {
        const x = num(['DirichletCharacter', 45, j, a]);
        const y = num(['DirichletCharacter', 45, j, b]);
        const xy = num(['DirichletCharacter', 45, j, a * b]);
        expect(x.re * y.re - x.im * y.im).toBeCloseTo(xy.re, 12);
        expect(x.re * y.im + x.im * y.re).toBeCloseTo(xy.im, 12);
      }
  });

  test('an index out of range, or a symbolic one, stays unevaluated', () => {
    expect(ce.box(['DirichletCharacter', 5, 9, 2]).evaluate().toString()).toBe(
      'DirichletCharacter(5, 9, 2)'
    );
    expect(ce.box(['DirichletCharacter', 5, 0, 2]).evaluate().operator).toBe(
      'DirichletCharacter'
    );
    expect(ce.box(['DirichletCharacter', 5, 2, 'n']).evaluate().operator).toBe(
      'DirichletCharacter'
    );
  });
});

