describe('DirichletL (#395)', () => {
  for (const [k, j, values] of lValues) {
    test(`L(s, χ_${j} mod ${k}) at twelve s, against mpmath / Wolfram`, () => {
      values.forEach(([re, im], i) => {
        const got = num(['DirichletL', k, j, sValues[i]]);
        const tol = 1e-9 * Math.max(1, Math.hypot(re, im));
        expect([i, Math.abs(got.re - re) <= tol]).toEqual([i, true]);
        expect([i, Math.abs(got.im - im) <= tol]).toEqual([i, true]);
      });
    });
  }

  const exact: [unknown, string][] = [
    [['DirichletL', 1, 1, 2], '1/6 * pi^2'],
    [['DirichletL', 1, 1, 1], '~oo'],
    [['DirichletL', 5, 1, 1], '~oo'],
    [['DirichletL', 3, 2, -2], '-2/9'],
    [['DirichletL', 5, 2, -1], '0'],
    [['DirichletL', 8, 2, -1], '-1'],
    [['DirichletL', 5, 3, -3], '2'],
    [['DirichletL', 8, 2, -3], '11'],
    [['DirichletL', 3, 2, 0], '1/3'],
    [['DirichletL', 5, 2, 0], '(3/5 + 1/5i)'],
    [['DirichletL', 12, 1, 's'], '(1 - 2^(-s)) * (1 - 3^(-s)) * Zeta(s)'],
    // No closed form at a positive integer: stays symbolic under evaluate().
    [['DirichletL', 5, 2, 2], 'DirichletL(5, 2, 2)'],
    [['DirichletL', 3, 2, ['Rational', 1, 2]], 'DirichletL(3, 2, 1/2)'],
    // Out of range or too large a modulus.
    [['DirichletL', 5, 9, 2], 'DirichletL(5, 9, 2)'],
    [['DirichletL', 5000, 2, 2], 'DirichletL(5000, 2, 2)'],
  ];
  for (const [json, expected] of exact) {
    test(`${JSON.stringify(json)} = ${expected} (evaluate)`, () => {
      expect(
        ce
          .box(json as never)
          .evaluate()
          .toString()
      ).toBe(expected);
    });
  }

  test('listable in s', () => {
    expect(
      ce
        .box(['DirichletL', 1, 1, ['List', 1, 2, 4]])
        .evaluate()
        .toString()
    ).toBe('[~oo,1/6 * pi^2,1/90 * pi^4]');
  });

  test('a float s gives a float under evaluate()', () => {
    expect(ce.box(['DirichletL', 3, 2, 1.5]).evaluate().toString()).toBe(
      '0.703968244868733261668'
    );
  });

  test('the mod-4 odd character is the Dirichlet beta function: L(1) = π/4, L(3) = π³/32', () => {
    expect(num(['DirichletL', 4, 2, 1]).re).toBeCloseTo(Math.PI / 4, 14);
    expect(num(['DirichletL', 4, 2, 3]).re).toBeCloseTo(Math.PI ** 3 / 32, 14);
  });

  test('L(1, χ_{-3}) = π/(3√3), through the Laurent series at s = 1', () => {
    expect(num(['DirichletL', 3, 2, 1]).re).toBeCloseTo(
      Math.PI / (3 * Math.sqrt(3)),
      14
    );
  });

  test('no jump where the Laurent series hands over to the Hurwitz sum (|s − 1| = 1/4)', () => {
    const below = num(['DirichletL', 8, 2, 1.2499999]).re;
    const above = num(['DirichletL', 8, 2, 1.2500001]).re;
    expect(Math.abs(below - above)).toBeLessThan(1e-6);
    expect(num(['DirichletL', 8, 2, 1.25]).re).toBeCloseTo(
      0.71072491969581705627,
      14
    );
  });

  test('near s = 1 (L(1.001, χ_{-3}))', () => {
    expect(num(['DirichletL', 3, 2, 1.001]).re).toBeCloseTo(
      0.604822401878057545679203964526,
      14
    );
  });

  describe('real s follows ce.precision', () => {
    const cases: [number, number, number, string][] = [
      [3, 2, 1.5, '0.703968244868733261667638559149'],
      [4, 2, 2.5, '0.948622174037054707445675768037'],
      [5, 3, 0.3, '0.141950805075155589486116749979'],
      [8, 2, 1.3, '0.725789184778703481922443138062'],
    ];
    for (const [k, j, s, expected] of cases) {
      test(`L(${s}, χ_${j} mod ${k}) to 30 digits`, () => {
        const precision = ce.precision;
        ce.precision = 30;
        try {
          const got = ce.box(['DirichletL', k, j, s]).N();
          expect(Math.abs(got.re - Number(expected))).toBeLessThan(1e-15);
          expect(got.toString().slice(0, 30)).toBe(expected.slice(0, 30));
        } finally {
          ce.precision = precision;
        }
      });
    }

    test('the principal character: ζ(3.5)(1 − 2^−3.5)(1 − 3^−3.5) to 30 digits', () => {
      const precision = ce.precision;
      ce.precision = 30;
      try {
        expect(
          ce.box(['DirichletL', 12, 1, 3.5]).N().toString().slice(0, 30)
        ).toBe('1.00517995570446233873987530541'.slice(0, 30));
      } finally {
        ce.precision = precision;
      }
    });
  });

  test('the principal character at a complex s: (1 − 2^−s) ζ(s), s = 1 + i', () => {
    const got = num(['DirichletL', 2, 1, ['Complex', 1, 1]]);
    expect(got.re).toBeCloseTo(0.6543589174072331, 12);
    expect(got.im).toBeCloseTo(-0.3843763502147996, 12);
  });
});

