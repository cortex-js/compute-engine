import { ComputeEngine } from '../../src/compute-engine';
import type { MathJsonExpression } from '../../src/math-json/types';
import { isFunction } from '../../src/compute-engine/boxed-expression/type-guards';
import { factorNumberFieldExpression } from '../../src/compute-engine/polynomial/boxed-number-field';

const square: MathJsonExpression = ['Power', 'x', 2];
const cube: MathJsonExpression = ['Power', 'x', 3];
const sqrt2: MathJsonExpression = ['Sqrt', 2];
const alpha = (coefficients: number[]): MathJsonExpression => [
  'AlgebraicGenerator',
  ['List', ...coefficients],
];

describe('Factor over an explicit number field', () => {
  let ce: ComputeEngine;
  beforeEach(() => {
    ce = new ComputeEngine();
  });
  const request = (f: MathJsonExpression, g: MathJsonExpression) =>
    ce.box(['Factor', f, 'x', g]);

  test.each([
    [
      sqrt2,
      ['Add', square, -2],
      ['Multiply', ['Add', 'x', ['Negate', sqrt2]], ['Add', 'x', sqrt2]],
    ],
    [
      'ImaginaryUnit',
      ['Add', square, 1],
      [
        'Multiply',
        ['Add', 'x', ['Negate', 'ImaginaryUnit']],
        ['Add', 'x', 'ImaginaryUnit'],
      ],
    ],
    [
      ['Root', 2, 3],
      ['Add', cube, -2],
      [
        'Multiply',
        ['Add', 'x', ['Negate', ['Root', 2, 3]]],
        [
          'Add',
          square,
          ['Multiply', 'x', ['Root', 2, 3]],
          ['Power', ['Root', 2, 3], 2],
        ],
      ],
    ],
  ] as MathJsonExpression[][])(
    'factors over the field generated by %j',
    (g, f, expected) => {
      const result = request(f, g).evaluate();
      expect(result.isValid).toBe(true);
      expect(result.isSame(ce.box(expected))).toBe(true);
    }
  );

  test('omitting the field retains rational factoring', () => {
    const f: MathJsonExpression = ['Add', square, -2];
    expect(ce.box(['Factor', f, 'x']).evaluate().isSame(ce.box(f))).toBe(true);
  });

  test('parses the ordinary LaTeX Factor call with a field argument', () => {
    const result = ce
      .parse('\\operatorname{Factor}(x^2-2,x,\\sqrt{2})')
      .evaluate();
    expect(result.isSame(ce.parse('(x-\\sqrt{2})(x+\\sqrt{2})'))).toBe(true);
  });

  // On the parse route, the held list arrives as `Delimiter(List(…))`.
  test.each([
    ['[-2,0,1]', '2x^2-4'],
    ['[-\\frac{1}{2},0,1]', '2x^2-1'],
  ])('parses AlgebraicGenerator(%s) written with brackets', (list, p) => {
    const g = `\\operatorname{AlgebraicGenerator}(${list})`;
    expect(ce.parse(g).evaluate().isValid).toBe(true);
    const result = ce.parse(`\\operatorname{Factor}(${p}, x, ${g})`).evaluate();
    expect(isFunction(result, 'Multiply')).toBe(true);
    const factors = isFunction(result) ? result.ops : [];
    expect(JSON.stringify(result.json)).not.toContain('Delimiter');
    expect(factors.filter((f) => f.has('x'))).toHaveLength(2);
  });

  test('an unevaluated parse-route request holds canonical operands', () => {
    const result = ce
      .parse('\\operatorname{Factor}(2x^2-1, x, \\pi)')
      .evaluate();
    expect(isFunction(result, 'Factor')).toBe(true);
    expect(JSON.stringify(result.json)).not.toContain('InvisibleOperator');
    expect(isFunction(result) && result.op1.isSame(ce.parse('2x^2-1'))).toBe(
      true
    );
  });

  test('a moderate request over a degree-8 field completes', () => {
    // The generator is a root of the minimal polynomial of √2+√3+√5.
    const g = alpha([576, 0, -960, 0, 352, 0, -40, 0, 1]);
    const result = request(['Add', ['Power', 'x', 13], -7], g).evaluate();
    expect(result.operator).not.toBe('Factor');
  });

  test('reads an exact complex coefficient with a rational part', () => {
    // 3/4 + i = (1 + i/2)^2, so x^2 - (3/4 + i) splits over Q(i).
    const result = request(
      ['Subtract', square, ['Add', ['Rational', 3, 4], 'ImaginaryUnit']],
      'ImaginaryUnit'
    ).evaluate();
    expect(isFunction(result, 'Multiply')).toBe(true);
  });

  test.each([
    [['AlgebraicGenerator', 5]],
    [['AlgebraicGenerator']],
    [['AlgebraicGenerator', ['List', -2, 0, 1], 3]],
  ] as [MathJsonExpression][])(
    'a malformed generator %j is invalid when it is boxed',
    (g) => {
      expect(ce.box(g).isValid).toBe(false);
    }
  );

  test('a cancellation from the caller is rethrown unchanged', () => {
    const stop = new Error('stop');
    let calls = 0;
    expect(() =>
      factorNumberFieldExpression(
        ce.box(['Add', ['Power', 'x', 8], -2]),
        'x',
        ce.box(['Root', 2, 8]),
        {
          check: () => {
            if (++calls > 2) throw stop;
          },
        }
      )
    ).toThrow(stop);
  });

  describe('a power of a generator is reduced modulo its polynomial', () => {
    // α is a root of t² - 2, β a root of t³ - t - 1.
    const a = alpha([-2, 0, 1]);
    const b = alpha([-1, -1, 0, 1]);
    test.each([
      [['Power', a, 2], 2],
      [
        ['Power', a, 3],
        ['Multiply', 2, a],
      ],
      [
        ['Power', b, 3],
        ['Add', b, 1],
      ],
      [
        ['Power', b, 4],
        ['Add', ['Power', b, 2], b],
      ],
    ] as [MathJsonExpression, MathJsonExpression][])('%j', (power, reduced) => {
      expect(ce.box(power).isSame(ce.box(reduced))).toBe(true);
    });
    test('in a product and in Expand', () => {
      expect(ce.box(['Multiply', a, a]).evaluate().isSame(2)).toBe(true);
      const factored = request(['Subtract', square, 2], a).evaluate();
      expect(
        ce
          .box(['Expand', factored.json])
          .evaluate()
          .isSame(ce.box(['Subtract', square, 2]))
      ).toBe(true);
    });
    test('below the degree, negative and large powers are kept', () => {
      for (const k of [1, -2, 200])
        expect(ce.box(['Power', b, k]).operator).toBe(
          k === 1 ? 'AlgebraicGenerator' : 'Power'
        );
    });
    test('a reducible or malformed generator is not reduced', () => {
      // t² - 1 is reducible: the error of the generator is kept.
      const power = ce.box(['Power', alpha([-1, 0, 1]), 2]);
      expect(power.operator).toBe('Power');
      expect(power.evaluate().isValid).toBe(false);
    });
    test('trailing zero coefficients do not change the degree', () => {
      // [1, 0, 1, 0] is t² + 1, so α² = -1.
      expect(ce.box(['Power', alpha([1, 0, 1, 0]), 2]).isSame(-1)).toBe(true);
    });
    test('the reduction is exact under N()', () => {
      expect(
        ce
          .box(['Power', a, 3])
          .N()
          .isSame(ce.box(['Multiply', 2, a]))
      ).toBe(true);
    });
    test('on the parse route', () => {
      expect(
        ce
          .parse('\\operatorname{AlgebraicGenerator}([-2,0,1])^2')
          .evaluate()
          .isSame(2)
      ).toBe(true);
    });
  });

  test('supports Apply and resolves stored polynomial operands', () => {
    const f: MathJsonExpression = ['Add', square, -2];
    ce.assign('p', f);
    const expected = request(f, sqrt2).evaluate();
    expect(request('p', sqrt2).evaluate().isSame(expected)).toBe(true);
    expect(
      ce.box(['Apply', 'Factor', f, 'x', sqrt2]).evaluate().isSame(expected)
    ).toBe(true);
  });

  test('reduces exact algebraic coefficients with a nonmonic defining polynomial', () => {
    const g = alpha([-4, 0, 0, 2]);
    expect(request(['Subtract', ['Power', g, 3], 2], g).evaluate().json).toBe(
      0
    );
  });

  test('keeps rational defining coefficients exact during numeric evaluation', () => {
    const g = ce.box([
      'AlgebraicGenerator',
      ['List', ['Rational', -2, 3], 0, 0, 1],
    ]);
    expect(g.N().json).toEqual(g.json);
  });

  test('numeric evaluation does not change the explicitly selected field', () => {
    const g: MathJsonExpression = [
      'AlgebraicGenerator',
      ['List', ['Rational', -2, 3], 0, 0, 1],
    ];
    const call = request(['Subtract', cube, ['Rational', 2, 3]], g);
    expect(call.N().json).toEqual(call.evaluate().json);
    expect(call.N().operator).toBe('Multiply');
  });

  test('numeric evaluation preserves an unsupported exact field request', () => {
    const call = request(
      ['Add', square, ['Sqrt', 3], ['Rational', 2, 3]],
      sqrt2
    );
    // The request stays unevaluated with its exact operands: no float.
    const result = call.N();
    expect(result.operator).toBe('Factor');
    expect(result.isSame(call.evaluate())).toBe(true);
    expect(JSON.stringify(result.json)).toContain('["Sqrt",3]');
    expect(JSON.stringify(result.json)).toContain('["Rational",2,3]');
  });

  test('shorthand radical factors can be factored again without changing fields', () => {
    const g: MathJsonExpression = ['Root', 2, 3];
    const result = request(['Add', cube, -2], g).evaluate();
    expect(request(result.json, g).evaluate().json).toEqual(result.json);
  });

  test.each([
    ['List', 0],
    ['List', -1, 0, 1],
    ['List', 1.1, 0, 1],
    ['List', 'Pi', 1],
  ] as MathJsonExpression[])(
    'rejects invalid or reducible abstract generator %j',
    (list) => {
      expect(ce.box(['AlgebraicGenerator', list]).evaluate().isValid).toBe(
        false
      );
    }
  );

  test('accepts trailing zero coefficients in the defining polynomial', () => {
    expect(ce.box(alpha([1, 0, 1, 0])).evaluate().isValid).toBe(true);
  });

  test.each([
    [-2, 0, 0, 1],
    [-1, -1, 0, 0, 0, 1],
  ])(
    'general abstract field factors its defining polynomial %j',
    (...coefficients) => {
      const g = alpha(coefficients);
      const f: MathJsonExpression = [
        'Add',
        ...coefficients.map((c, i): MathJsonExpression => [
          'Multiply',
          c,
          ['Power', 'x', i],
        ]),
      ];
      const result = request(f, g).evaluate();
      expect(result.isValid).toBe(true);
      expect(result.operator).toBe('Multiply');
      expect(JSON.stringify(result.json)).toContain('AlgebraicGenerator');
      const difference: MathJsonExpression = [
        'Subtract',
        ['Expand', result.json],
        f,
      ];
      expect(request(difference, g).evaluate().json).toEqual(0);
      const other = new ComputeEngine();
      const restored = other.box(JSON.parse(JSON.stringify(result.json)));
      expect(restored.json).toEqual(result.json);
      expect(
        other
          .box(['Factor', ['Subtract', ['Expand', restored.json], f], 'x', g])
          .evaluate().json
      ).toEqual(0);
      expect(JSON.stringify(restored.N().json)).toContain('AlgebraicGenerator');
    }
  );

  test('retains rational content and repeated factors', () => {
    const f: MathJsonExpression = [
      'Multiply',
      ['Rational', 3, 7],
      ['Power', ['Add', square, -2], 3],
    ];
    const expected: MathJsonExpression = [
      'Multiply',
      ['Rational', 3, 7],
      ['Power', ['Add', 'x', sqrt2], 3],
      ['Power', ['Add', 'x', ['Negate', sqrt2]], 3],
    ];
    expect(request(f, sqrt2).evaluate().isSame(ce.box(expected))).toBe(true);
  });

  test.each([
    { coefficients: [-2, 0, 0, 1] },
    { coefficients: [1, 0, 0, 0, 1] },
    { coefficients: [-1, -1, 0, 0, 0, 1] },
  ])('factors expanded families over $coefficients', ({ coefficients }) => {
    const g = alpha(coefficients);
    for (const shift of [1, 2, 3]) {
      const product: MathJsonExpression = [
        'Multiply',
        ['Rational', shift, 7],
        ['Power', ['Add', 'x', g, shift], 2],
        ['Add', 'x', ['Negate', g], shift + 1],
      ];
      const expanded = ce.box(['Expand', product]).evaluate();
      const result = request(expanded.json, g).evaluate();
      expect(result.isSame(ce.box(product))).toBe(true);
    }
  });

  test('preserves large exact coefficients at low working precision', () => {
    ce.precision = 20;
    const large: MathJsonExpression = {
      num: '100000000000000000000000000000000000000000000000000001',
    };
    const product: MathJsonExpression = [
      'Multiply',
      ['Add', 'x', large, sqrt2],
      ['Subtract', 'x', sqrt2],
    ];
    const expanded = ce.box(['Expand', product]).evaluate();
    expect(
      request(expanded.json, sqrt2).evaluate().isSame(ce.box(product))
    ).toBe(true);
  });

  test('reads exact Gaussian coefficients, not their floating projections', () => {
    const f: MathJsonExpression = [
      'Add',
      square,
      ['Multiply', -3, 'x'],
      ['Complex', 3, 1],
    ];
    const expected: MathJsonExpression = [
      'Multiply',
      ['Add', 'x', ['Complex', -1, -1]],
      ['Add', 'x', ['Complex', -2, 1]],
    ];
    expect(
      request(f, 'ImaginaryUnit').evaluate().isSame(ce.box(expected))
    ).toBe(true);
  });

  test('divides coefficients in the selected field', () => {
    const g = alpha([-2, 0, 0, 1]);
    const f: MathJsonExpression = ['Subtract', 'x', ['Divide', 1, g]];
    const expected: MathJsonExpression = [
      'Subtract',
      'x',
      ['Multiply', ['Rational', 1, 2], ['Power', g, 2]],
    ];
    expect(request(f, g).evaluate().isSame(ce.box(expected))).toBe(true);
  });

  test('protects the polynomial variable and resolves a bound generator', () => {
    ce.assign('x', 5);
    ce.assign('a', sqrt2);
    const result = request(['Add', square, -2], 'a').evaluate();
    expect(result.symbols).toContain('x');
    expect(result.operator).toBe('Multiply');
  });

  test.each([0, 3, ['Rational', -2, 7]] as MathJsonExpression[])(
    'handles constant %j',
    (f) => {
      expect(request(f, sqrt2).evaluate().isSame(ce.box(f))).toBe(true);
    }
  );

  test.each([
    [['Add', square, -2], 'Pi'],
    [['Add', square, -2], 1.4142135623730951],
    [['Add', square, ['Sqrt', 3]], sqrt2],
    [['Add', square, 'y'], sqrt2],
    [['Divide', 1, 'x'], sqrt2],
    [['Sin', 'x'], sqrt2],
    [['Add', square, 0.1], sqrt2],
    [['Power', 'x', 129], sqrt2],
    [['Add', square, -2], alpha([-1, 0, 1])],
  ] as MathJsonExpression[][])(
    'does not change domain or approximate unsupported input %j',
    (f, g) => {
      const result = request(f, g).evaluate();
      expect(result.operator).toBe('Factor');
    }
  );

  test('returns no result when certification exhausts its budget', () => {
    expect(
      factorNumberFieldExpression(
        ce.box(['Add', square, -2]),
        'x',
        ce.box(sqrt2),
        { maxOperations: 0 }
      )
    ).toBeUndefined();
  });

  test('does not swallow cancellation', () => {
    const cancelled = new Error('cancelled');
    expect(() =>
      factorNumberFieldExpression(ce.box(square), 'x', ce.box(sqrt2), {
        check: () => {
          throw cancelled;
        },
      })
    ).toThrow(cancelled);
  });

  test('does not swallow a caller RangeError', () => {
    const cancelled = new RangeError('caller cancellation');
    expect(() =>
      factorNumberFieldExpression(ce.box(square), 'x', ce.box(sqrt2), {
        check: () => {
          throw cancelled;
        },
      })
    ).toThrow(cancelled);
  });
});
