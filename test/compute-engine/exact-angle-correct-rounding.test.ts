/** The real part and the imaginary part of a number literal, as big
 * decimals. */
function parts(ce: ComputeEngine, x: unknown): [BigDecimal, BigDecimal] {
  const e = ce.box(x as any).N() as any;
  const re = e.bignumRe ?? new BigDecimal(e.re);
  const im = e.bignumIm ?? new BigDecimal(e.im);
  return [re, im];
}

const angle = (k: number) => ['Multiply', 'Pi', ['Rational', k, 12]];

describe('e^{iθ}, cos θ and sin θ of an exact θ = kπ/12 are correctly rounded', () => {
  test.each(TABLE)('precision %d, k = %d', (precision, k, cos, sin) => {
    const ce = new ComputeEngine();
    ce.precision = precision;
    const [re, im] = parts(ce, [
      'Exp',
      ['Multiply', 'ImaginaryUnit', 'Pi', ['Rational', k, 12]],
    ]);
    expect(re.toString()).toBe(new BigDecimal(cos).toString());
    expect(im.toString()).toBe(new BigDecimal(sin).toString());
    // The circular functions of the same exact angle
    expect(parts(ce, ['Cos', angle(k)])[0].toString()).toBe(
      new BigDecimal(cos).toString()
    );
    expect(parts(ce, ['Sin', angle(k)])[0].toString()).toBe(
      new BigDecimal(sin).toString()
    );
    // cosh(iθ) = cos θ, from the same exact angle
    expect(
      parts(ce, ['Cosh', ['Multiply', 'ImaginaryUnit', angle(k)]])[0].toString()
    ).toBe(new BigDecimal(cos).toString());
  });

  test('e^{−7iπ/6} at 21 digits', () => {
    const ce = new ComputeEngine();
    expect(ce.parse('e^{-7i\\pi/6}').N().toString()).toBe(
      '(-0.866025403784438646764 + 0.5i)'
    );
  });

  test('the working precision is restored', () => {
    const ce = new ComputeEngine();
    ce.precision = 30;
    const before = BigDecimal.precision;
    ce.parse('e^{i\\pi/6}').N();
    expect(BigDecimal.precision).toBe(before);
  });
});
