/** The reserved-word set for a GPU shader language, or an empty set. */
function gpuReservedWords(language?: string): ReadonlySet<string> {
  if (language === 'glsl') return GLSL_RESERVED;
  return new Set();
}

/** Whether `id` is a reserved word in the shader language `language`. */
export function gpuIsReservedWord(id: string, language?: string): boolean {
  return gpuReservedWords(language).has(id);
}
