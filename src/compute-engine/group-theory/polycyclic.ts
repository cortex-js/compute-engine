/**
 * Coordinates and induced sequences for bounded finite table groups.
 * Every suffix is normal in its predecessor and has a cyclic factor. Public
 * positions and depths start at one; element indices belong to the ambient table.
 * Full coordinate dictionaries make repeated membership and coordinate queries
 * cheap, but require O(|H| r) storage for a rank-r sequence generating H.
 */
import {
  FiniteGroupTable,
  FiniteSubgroup,
  GroupWork,
  GroupInputError,
} from './finite-group.js';

/**
 * A validated subnormal cyclic series for a bounded finite table group.
 * Coordinates use g1^e1 ... gr^er with 0 <= ei < relativeOrders[i].
 * The complete coordinate dictionary costs O(|H| r) storage; this backend
 * supports finite solvable groups, not arbitrary polycyclic presentations.
 */
export class FinitePcgs {
  readonly #group: FiniteGroupTable;
  readonly #sequence: readonly number[];
  readonly #series: readonly FiniteSubgroup[];
  readonly #relativeOrders: readonly number[];
  readonly #coordinates: ReadonlyMap<number, readonly number[]>;
  readonly #parent: FinitePcgs | undefined;
  private constructor(
    group: FiniteGroupTable,
    sequence: number[],
    series: FiniteSubgroup[],
    orders: number[],
    coordinates: Map<number, readonly number[]>,
    parent?: FinitePcgs
  ) {
    this.#group = group;
    this.#sequence = sequence;
    this.#series = series;
    this.#relativeOrders = orders;
    this.#coordinates = coordinates;
    this.#parent = parent;
  }
  static fromSequence(
    group: FiniteGroupTable,
    input: readonly number[],
    work: GroupWork,
    parent?: FinitePcgs
  ): FinitePcgs {
    if (!Array.isArray(input) || input.length > 256)
      throw new GroupInputError('invalid-pc-sequence');
    const session = group.session(work),
      sequence = [...input];
    sequence.forEach((x) => group.element(x));
    // Build each tail from the already compressed generators of its suffix.
    const series: FiniteSubgroup[] = Array(sequence.length + 1);
    series[sequence.length] = session.trivial;
    for (let i = sequence.length - 1; i >= 0; i--)
      series[i] = session.generated([sequence[i], ...series[i + 1].generators]);
    const orders: number[] = [];
    for (let i = 0; i < sequence.length; i++) {
      if (!session.isNormal(series[i], series[i + 1]))
        throw new GroupInputError('pc-tail-is-not-normal');
      orders.push(session.index(series[i], series[i + 1]));
    }
    const coordinates = new Map<number, readonly number[]>([[0, []]]);
    // Build suffixes from the right, preserving g1^e1 ... gn^en order.
    for (let i = sequence.length - 1; i >= 0; i--) {
      const suffix = [...coordinates];
      coordinates.clear();
      let power = 0;
      for (let e = 0; e < orders[i]; e++) {
        for (const [x, v] of suffix) {
          const y = session.mul(power, x);
          if (coordinates.has(y))
            throw new GroupInputError('nonunique-pc-coordinates');
          coordinates.set(y, [e, ...v]);
        }
        power = session.mul(power, sequence[i]);
      }
    }
    if (coordinates.size !== series[0].order)
      throw new GroupInputError('incomplete-pc-coordinates');
    if (parent !== undefined) {
      if (parent.group !== group || !session.subset(parent.subgroup, series[0]))
        throw new GroupInputError('incompatible-parent-pcgs');
      let previous = 0;
      for (const x of sequence) {
        const depth = parent.depth(x, work);
        if (x === 0 || depth <= previous)
          throw new GroupInputError('pcgs-is-not-induced');
        previous = depth;
      }
      // Triangular generators alone are insufficient for composite relative orders:
      // every intersection with a parent tail must be generated by the matching suffix.
      for (let i = 0; i < parent.sequence.length; i++) {
        const tail = session.generated(
          sequence.filter((x) => parent.depth(x, work) > i)
        );
        if (
          !session.equal(
            tail,
            session.intersection(series[0], parent.series[i])
          )
        )
          throw new GroupInputError('incomplete-induced-pcgs');
      }
    }
    return new FinitePcgs(group, sequence, series, orders, coordinates, parent);
  }
  static compute(
    group: FiniteGroupTable,
    work: GroupWork,
    subgroup?: FiniteSubgroup
  ): FinitePcgs | undefined {
    const session = group.session(work),
      target = subgroup ?? session.whole;
    session.receive(target);
    const derived = session.series('derived', target);
    if (derived.at(-1)!.order !== 1) return undefined;
    const sequence: number[] = [];
    let tail = session.trivial;
    // Refine each abelian derived factor from below. Every intermediate
    // subgroup is normal in the factor's numerator; adjoining a prime-order
    // coset therefore gives a cyclic subnormal step without a lattice search.
    for (let i = derived.length - 2; i >= 0; i--) {
      const upper = derived[i];
      for (const x of upper.members) {
        work.tick();
        while (!tail.has(x)) {
          let power = x,
            relative = 1;
          while (!tail.has(power)) {
            power = session.mul(power, x);
            relative++;
          }
          let prime = 2;
          while (relative % prime !== 0) {
            work.tick();
            prime++;
          }
          const generator = session.pow(x, BigInt(relative / prime));
          const next = session.generated([...tail.generators, generator]);
          if (next.order !== tail.order * prime)
            throw new Error('Invalid derived-factor refinement');
          sequence.unshift(generator);
          tail = next;
        }
      }
      if (!session.equal(tail, upper))
        throw new Error('Incomplete derived-factor refinement');
    }
    return FinitePcgs.fromSequence(group, sequence, work);
  }
  get group(): FiniteGroupTable {
    return this.#group;
  }
  get sequence(): readonly number[] {
    return this.#sequence;
  }
  get series(): readonly FiniteSubgroup[] {
    return this.#series;
  }
  get subgroup(): FiniteSubgroup {
    return this.#series[0];
  }
  get relativeOrders(): readonly number[] {
    return this.#relativeOrders;
  }
  get parent(): FinitePcgs | undefined {
    return this.#parent;
  }
  exponents(x: number, work: GroupWork): readonly number[] {
    work.tick(this.sequence.length + 1);
    this.group.element(x);
    const v = this.#coordinates.get(x);
    if (!v) throw new GroupInputError('element-outside-pcgs');
    return v;
  }
  element(exponents: readonly number[], work: GroupWork): number {
    if (!Array.isArray(exponents) || exponents.length !== this.sequence.length)
      throw new GroupInputError('invalid-pc-exponent-count');
    for (let i = 0; i < exponents.length; i++) {
      work.tick();
      if (
        !Number.isSafeInteger(exponents[i]) ||
        exponents[i] < 0 ||
        exponents[i] >= this.relativeOrders[i]
      )
        throw new GroupInputError('pc-exponent-out-of-range');
    }
    return this.linearCombination(exponents.map(BigInt), work);
  }
  linearCombination(exponents: readonly bigint[], work: GroupWork): number {
    if (!Array.isArray(exponents) || exponents.length !== this.sequence.length)
      throw new GroupInputError('invalid-pc-exponent-count');
    const session = this.group.session(work);
    let result = 0;
    for (let i = 0; i < exponents.length; i++)
      result = session.mul(result, session.pow(this.sequence[i], exponents[i]));
    return result;
  }
  depth(x: number, work: GroupWork): number {
    const v = this.exponents(x, work);
    const i = v.findIndex((e) => e !== 0);
    return i < 0 ? v.length + 1 : i + 1;
  }
  leadingExponent(x: number, work: GroupWork): number {
    const v = this.exponents(x, work);
    return v.find((e) => e !== 0) ?? 0;
  }
  relativeOrder(x: number, work: GroupWork): number {
    const session = this.group.session(work),
      d = this.depth(x, work) - 1;
    if (x === 0) return 1;
    let power = 0;
    for (let r = 1; r <= this.relativeOrders[d]; r++) {
      power = session.mul(power, x);
      if (this.series[d + 1].has(power)) return r;
    }
    throw new Error('Pc series has invalid relative order');
  }
  head(x: number, depth: number, work: GroupWork): number {
    if (
      !Number.isSafeInteger(depth) ||
      depth < 1 ||
      depth > this.sequence.length + 1
    )
      throw new GroupInputError('invalid-pc-depth');
    return this.element(
      this.exponents(x, work).map((e, i) => (i < depth - 1 ? e : 0)),
      work
    );
  }
  reduced(x: number, y: number, work: GroupWork): number {
    const d = this.depth(x, work);
    if (!y || d !== this.depth(y, work))
      throw new GroupInputError(
        'pc-reduction-requires-equal-nonidentity-depth'
      );
    const session = this.group.session(work);
    let result = x;
    for (let e = 0; e < this.relativeOrder(y, work); e++) {
      if (this.depth(result, work) > d) return result;
      result = session.mul(session.inv(y), result);
    }
    throw new GroupInputError('pc-leading-coefficient-not-divisible');
  }
  /**
   * Intersect H with every parent tail. Its image in the next cyclic factor
   * is generated by the least positive leading exponent, including composite
   * factors. Lexicographic suffix order makes the choice deterministic.
   * The table scan costs O(r |H|), plus sorting candidate coordinate vectors.
   */
  induced(h: FiniteSubgroup, work: GroupWork): FinitePcgs {
    const session = this.group.session(work);
    if (!session.subset(this.subgroup, h))
      throw new GroupInputError('not-a-pc-subgroup');
    const sequence: number[] = [];
    for (let i = 0; i < this.sequence.length; i++) {
      const intersection = session.intersection(h, this.series[i]);
      const candidates = intersection.members.filter(
        (x) => this.depth(x, work) === i + 1
      );
      if (!candidates.length) continue;
      candidates.sort((a, b) => {
        const va = this.exponents(a, work),
          vb = this.exponents(b, work);
        for (let j = i; j < va.length; j++)
          if (va[j] !== vb[j]) return va[j] - vb[j];
        return 0;
      });
      sequence.push(candidates[0]);
    }
    return FinitePcgs.fromSequence(this.group, sequence, work, this);
  }
  /**
   * Membership reduction in the parent coordinates. The residue stays in H*x
   * and is identity exactly when x belongs to H. Stop at the first leading
   * coefficient that H cannot eliminate; later coefficients do not repair it.
   * For a nonnormal H, this is not a canonical representative of the coset.
   */
  sift(x: number, work: GroupWork): number {
    const parent = this.parent;
    if (!parent) throw new GroupInputError('sifting-requires-induced-pcgs');
    parent.exponents(x, work);
    const session = this.group.session(work);
    for (const generator of this.sequence) {
      if (x === 0) return 0;
      const depth = parent.depth(generator, work);
      const residueDepth = parent.depth(x, work);
      if (residueDepth < depth) return x;
      if (residueDepth > depth) continue;
      const lead = parent.leadingExponent(generator, work);
      const relativeOrder = parent.relativeOrders[depth - 1];
      const exponent = parent.leadingExponent(x, work);
      let power = 0;
      while (
        power < relativeOrder &&
        (power * lead) % relativeOrder !== exponent
      ) {
        work.tick();
        power++;
      }
      if (power === relativeOrder) return x;
      x = session.mul(session.pow(generator, -BigInt(power)), x);
    }
    return x;
  }
  /** The least parent exponent vector in H*x; scans |H| vectors of length r. */
  canonical(x: number, work: GroupWork): number {
    if (!this.parent)
      throw new GroupInputError('canonical-reduction-requires-induced-pcgs');
    const parent = this.parent;
    parent.exponents(x, work);
    const session = this.group.session(work);
    let best = x,
      bestVector = parent.exponents(x, work);
    for (const h of this.subgroup.members) {
      const y = session.mul(h, x),
        vector = parent.exponents(y, work);
      for (let i = 0; i < vector.length; i++) {
        if (vector[i] === bestVector[i]) continue;
        if (vector[i] < bestVector[i]) {
          best = y;
          bestVector = vector;
        }
        break;
      }
    }
    return best;
  }
  factorThrough(
    other: FinitePcgs,
    x: number,
    work: GroupWork
  ): readonly [number, number] | undefined {
    if (other.group !== this.group)
      throw new GroupInputError('incompatible-pcgs-domains');
    this.group.element(x);
    const session = this.group.session(work);
    for (const a of this.subgroup.members) {
      const b = session.mul(session.inv(a), x);
      if (other.subgroup.has(b)) return [a, b];
    }
    return undefined;
  }
  /** Conjugate positions (i, j) mean gi^-1 gj gi; commutators mean [gi, gj]. */
  specialExponents(
    kind: 'power' | 'conjugate' | 'commutator',
    i: number,
    j: number | undefined,
    work: GroupWork
  ): readonly number[] {
    if (!Number.isSafeInteger(i) || i < 1 || i > this.sequence.length)
      throw new GroupInputError('invalid-pc-position');
    const session = this.group.session(work),
      a = this.sequence[i - 1];
    let x: number;
    if (kind === 'power')
      x = session.pow(a, BigInt(this.relativeOrders[i - 1]));
    else {
      if (!Number.isSafeInteger(j) || j! < 1 || j! > this.sequence.length)
        throw new GroupInputError('invalid-pc-position');
      const b = this.sequence[j! - 1];
      x =
        kind === 'conjugate'
          ? session.conjugate(b, a)
          : session.commutator(a, b);
    }
    return this.exponents(x, work);
  }
  quotient(n: FiniteSubgroup, work: GroupWork) {
    const session = this.group.session(work),
      quotient = session.quotient(this.subgroup, n);
    const pcgs = FinitePcgs.fromSequence(
      quotient.group,
      this.sequence.map((x) => quotient.projection[x]),
      work
    );
    return {
      quotient,
      group: quotient.group,
      projection: quotient.projection,
      representatives: quotient.representatives,
      pcgs,
    };
  }
}
