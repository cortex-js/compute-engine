import type { ComputeEngine } from '../compute-engine.js';
import type { BoxedDefinition } from '../compute-engine/global-types.js';
import { STANDARD_LIBRARIES } from '../compute-engine/library/library.js';

import { definitionDocs, type ParameterDoc } from './doc-tags.js';
import { epsilDescription, epsilExamples } from './example-spelling.js';
import { canonicalLibraryName, epsilNameOf } from './library-names.js';

//
// The description of a standard-library name: its kind, signature or type,
// description and reference link. `epsil doc` prints it, the language server
// renders it as a hover, and `epsilCompletions()` reads it for the detail of
// a library item.
//

/**
 * One documentation entry, as printed by `epsil doc`. `signature` is set
 * for operators, `type` (and `value`, when it has one) for symbols.
 */
export interface DocEntry {
  id: string;
  /** The Epsil spelling of a standard-library name (`sin` for `Sin`), when
   * it has one. See `src/epsil/library-names.ts`. */
  epsilName?: string;
  kind: 'function' | 'opaque' | 'constant' | 'variable';
  signature?: string;
  type?: string;
  value?: string;
  /** The paragraphs of the description. The tag lines of a `///` comment
   * (`@param`, `@key`, `@sample`, `@default`, `@example`) are not in it:
   * they are `parameters` and `examples`. */
  description?: string[];
  /** The documentation of the parameters of a function, keyed by parameter
   * name: the `parameters` field of its definition and the tags of its
   * `///` comment. */
  parameters?: Record<string, ParameterDoc>;
  /** The documentation of the parameters by position, for a definition
   * whose `parameters` field is a list: the entry `i` documents the
   * parameter `i` of each arm of the signature (`null` for one that it
   * leaves undocumented). */
  positionalParameters?: (ParameterDoc | null)[];
  /** The examples, each one line of Epsil source in the Epsil spelling
   * (`join([1, 2], [3, 4])`, which the definition writes
   * `Join([1, 2], [3, 4])`). */
  examples?: string[];
  keywords?: string[];
  url?: string;
  wikidata?: string;
  /** The entry of a standard-library name in the library reference on the
   * documentation site, which has more than this summary. See
   * `referencePath()`. */
  reference?: string;
}

/** The documentation site, which publishes the library reference. */
export const DOCS_SITE = 'https://epsil.dev';

/** The anchor the documentation site gives a heading (Docusaurus, after
 * github-slugger): lower case, no punctuation except `-` and `_`, each space
 * a `-`. */
export function headingAnchor(heading: string): string {
  return heading
    .toLowerCase()
    .trim()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

let libraryByName: Map<string, string> | undefined;

/** The standard library (`arithmetic`, `core`, …) that defines a name. */
export function libraryOf(name: string): string | undefined {
  if (!libraryByName) {
    libraryByName = new Map();
    for (const lib of STANDARD_LIBRARIES) {
      const blocks =
        lib.definitions === undefined
          ? []
          : Array.isArray(lib.definitions)
            ? lib.definitions
            : [lib.definitions];
      for (const block of blocks)
        for (const key of Object.keys(block))
          if (!key.startsWith('_') && !libraryByName.has(key))
            libraryByName.set(key, lib.name);
    }
  }
  return libraryByName.get(name);
}

/**
 * The path of a definition's entry in the library reference, without the
 * site: `/reference/arithmetic/#sqrt`. The reference page of each library is
 * generated by `scripts/build-library-reference.ts`, which heads each entry
 * with the Epsil spelling (the MathJSON name when there is none); the anchor
 * is that heading's. The site search (`scripts/build-search-symbols.ts`)
 * uses the same path.
 */
export function referencePath(
  id: string,
  epsilName: string | undefined
): string | undefined {
  const library = libraryOf(id);
  if (library === undefined) return undefined;
  return `/reference/${library}/#${headingAnchor(epsilName ?? id)}`;
}

/**
 * The documentation entry for one exact name, or `undefined` when the engine
 * has no definition for it.
 *
 * Exported as the single describer of a library name: `epsil doc` prints it,
 * and the language server renders it as a hover, so the editor and the CLI
 * cannot drift apart on what a function is or what it takes.
 */
export function describeName(
  engine: ComputeEngine,
  name: string
): DocEntry | undefined {
  const def = engine.lookupDefinition(name);
  if (!def) {
    // An Epsil spelling (`sin`) with no engine binding of its own describes
    // the library name it stands for (`Sin`).
    const canonical = canonicalLibraryName(name);
    return canonical === undefined
      ? undefined
      : describeName(engine, canonical);
  }

  // The spelling and the reference belong to the STANDARD library's
  // definition: a user binding that shadows a library name (`let Sin = 5` on
  // a shared engine) is described as what it is, with neither.
  const isLibraryBinding =
    engine.contextStack[0]?.lexicalScope.bindings.get(name) === def;
  return describeDefinition(engine, name, def, isLibraryBinding);
}

/**
 * The examples of the definition of `name` that `describeName()` describes
 * (the visible one), or with `library` of the standard library's definition
 * (`describeLibraryName()`), as the definition and its `///` comment write
 * them. Empty when there is no definition.
 */
export function definitionSourceExamples(
  engine: ComputeEngine,
  name: string,
  library = false
): readonly string[] {
  const system = engine.contextStack[0]?.lexicalScope.bindings.get(name);
  const def = library ? system : engine.lookupDefinition(name);
  if (def === undefined) {
    const canonical = library ? undefined : canonicalLibraryName(name);
    return canonical === undefined
      ? []
      : definitionSourceExamples(engine, canonical);
  }
  const base = 'operator' in def ? def.operator : def.value;
  return definitionDocs(base, def === system).examples;
}

/**
 * The examples of `definitionSourceExamples()` in the Epsil spelling
 * (`epsilExamples()`). A spelling that the source declares at the place of
 * the editor (`sourceNames`) is not written.
 */
export function definitionExamples(
  engine: ComputeEngine,
  name: string,
  sourceNames?: { has(name: string): boolean },
  library = false
): string[] {
  const examples = definitionSourceExamples(engine, name, library);
  return examples.length === 0
    ? []
    : epsilExamples(engine, examples, sourceNames);
}

/**
 * The documentation entry of the standard library's definition of one exact
 * name, or `undefined` when the standard library does not define it. A
 * binding of the engine that shadows the name is not read: this is the
 * meaning of a qualified name (`std::e` after `let e = 5`). No Epsil
 * spelling is resolved here.
 */
export function describeLibraryName(
  engine: ComputeEngine,
  name: string
): DocEntry | undefined {
  const def = engine.contextStack[0]?.lexicalScope.bindings.get(name);
  return def === undefined
    ? undefined
    : describeDefinition(engine, name, def, true);
}

/** The documentation entry of the definition `def` of `name`.
 * `isLibraryBinding` says that it is the standard library's definition. */
function describeDefinition(
  engine: ComputeEngine,
  name: string,
  def: BoxedDefinition,
  isLibraryBinding: boolean
): DocEntry {
  const entry: DocEntry = { id: name, kind: 'variable' };
  const epsilName = epsilNameOf(name);
  if (
    epsilName !== undefined &&
    canonicalLibraryName(epsilName) === name &&
    isLibraryBinding
  )
    entry.epsilName = epsilName;
  if (isLibraryBinding) {
    const path = referencePath(name, entry.epsilName);
    if (path !== undefined) entry.reference = DOCS_SITE + path;
  }

  const base = 'operator' in def ? def.operator : def.value;
  const docs = definitionDocs(
    {
      description: base.description,
      examples: base.examples,
      parameters: 'operator' in def ? def.operator.parameters : undefined,
    },
    isLibraryBinding
  );
  // The description writes its code with the MathJSON names, as the
  // examples do: its code spans are shown in the Epsil spelling too.
  if (docs.description !== undefined)
    entry.description = epsilDescription(engine, docs.description);
  if (docs.parameters.size > 0)
    entry.parameters = Object.fromEntries(docs.parameters);
  if (docs.positional.some((doc) => doc !== undefined))
    entry.positionalParameters = docs.positional.map((doc) => doc ?? null);
  if (docs.examples.length > 0)
    entry.examples = epsilExamples(engine, docs.examples);
  if (base.keywords && base.keywords.length > 0) entry.keywords = base.keywords;
  if (base.url) entry.url = base.url;
  if (base.wikidata) entry.wikidata = base.wikidata;

  // The kind, the signature and the type are read from the definition, by
  // the rules of `operatorInfo()` and `symbolInfo()`, which read the visible
  // definition of the name only.
  if ('operator' in def) {
    const operator = def.operator;
    entry.kind =
      operator.evaluate || operator.collection ? 'function' : 'opaque';
    if (operator.signature) entry.signature = operator.signature.toString();
    return entry;
  }

  entry.kind = def.value.isConstant ? 'constant' : 'variable';
  entry.type = def.value.type.toString();
  if (entry.kind === 'constant') {
    // The value of a constant is part of its documentation (`Pi` ≈ π).
    try {
      const value = def.value.value;
      if (value !== undefined && value !== null) entry.value = value.toString();
    } catch {
      // A value that cannot be computed is simply omitted.
    }
  }
  return entry;
}
