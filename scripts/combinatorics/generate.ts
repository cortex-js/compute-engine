// Generator and drift gate for data/combinatorics.
//
// Reads the area source tables (src/compute-engine/combinatorics/sources/: the
// Epsil text, which only this script and the tests import) and writes the files
// that derive from them:
//
//   src/compute-engine/combinatorics/compiled.ts
//                                              each Epsil definition as MathJSON, with
//                                              its head and FindStat identifier, so the
//                                              library never parses Epsil
//   data/combinatorics/findstat/matches.json   head -> FindStat identifier, domain,
//                                              and how many FindStat values it is held to
//   data/combinatorics/MANIFEST.json           counts
//
// and validates the hand-kept data: the example rows and the FindStat values
// fixtures. A match record says the definition equals FindStat's value on every
// fixture object; --values, the FindStat values test and the nightly hold it to
// that. A row without a FindStat identifier has no record and no fixture; its
// example rows hold it.
//
// Usage (from the repository root):
//   npx tsx scripts/combinatorics/generate.ts           write
//   npx tsx scripts/combinatorics/generate.ts --check   fail on drift
//   npx tsx scripts/combinatorics/generate.ts --values  write, and evaluate every fixture object
//   npx tsx scripts/combinatorics/generate.ts --check --values
//
// Neither writing nor --check evaluates a definition (seconds): they only
// compile the Epsil and compare the generated files. --values evaluates every
// head on every fixture object and fails on a difference with FindStat (about
// half an hour: each call runs the Epsil definition); the FindStat values test
// takes the small objects, and the nightly all of them.
//
// Exit codes: 0 = fresh; 1 = drift or invalid data; 2 = usage.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { ComputeEngine } from '../../src/compute-engine';
import { KERNELS } from '../../src/compute-engine/combinatorics/kernels';
import {
  COMBINATORICS_AREAS,
  loadCombinatorics,
} from '../../src/compute-engine/combinatorics/loader';
import { PARTITION_SOURCES } from '../../src/compute-engine/combinatorics/sources/partitions';
import { PERMUTATION_SOURCES } from '../../src/compute-engine/combinatorics/sources/permutations';
import type { Source } from '../../src/compute-engine/combinatorics/sources/source';

import { compileEpsil } from './epsil';

const root = resolve(dirname(process.argv[1]), '../..');
const data = join(root, 'data/combinatorics');
const compiledFile = join(root, 'src/compute-engine/combinatorics/compiled.ts');
const check = process.argv.includes('--check');
const evaluateValues = process.argv.includes('--values');
if (process.argv.slice(2).some((a) => a !== '--check' && a !== '--values')) {
  console.error('usage: generate.ts [--check] [--values]');
  process.exit(2);
}

const problems: string[] = [];

const SOURCES: Record<string, readonly Source[]> = {
  permutations: PERMUTATION_SOURCES,
  partitions: PARTITION_SOURCES,
};

// The compiled definitions come first: everything below runs them.
const rows: string[] = [];
const seen = new Set<string>();
for (const area of COMBINATORICS_AREAS) {
  rows.push(`  ${area.name}: [`);
  for (const source of SOURCES[area.name]) {
    if (seen.has(source.head)) problems.push(`${source.head}: declared twice`);
    seen.add(source.head);
    try {
      rows.push(
        `    [${JSON.stringify(source.head)}, ${JSON.stringify(source.findstat ?? null)}, ${JSON.stringify(compileEpsil(source.epsil))}],`
      );
    } catch (error) {
      problems.push(`${source.head}: ${(error as Error).message}`);
    }
  }
  rows.push('  ],');
}
for (const head of Object.keys(KERNELS))
  if (!seen.has(head)) problems.push(`${head}: a kernel without a row`);
const compiledSource = `// Generated by scripts/combinatorics/generate.ts from the tables in sources/.
// Do not edit; run \`npx tsx scripts/combinatorics/generate.ts\`.

import type { MathJsonExpression } from '../../math-json/types.js';
import type { CombinatoricsArea } from './areas.js';

type Row = readonly [
  head: string,
  findstat: string | null,
  literal: MathJsonExpression,
];

/** Each statistic's head, FindStat identifier and Epsil function literal as MathJSON. */
// prettier-ignore
export const COMPILED: Readonly<Record<CombinatoricsArea, readonly Row[]>> = {
${rows.join('\n')}
};
`;
const compiledStale =
  !existsSync(compiledFile) ||
  readFileSync(compiledFile, 'utf8') !== compiledSource;
if (problems.length === 0 && compiledStale) {
  if (check) {
    console.error(
      'src/compute-engine/combinatorics/compiled.ts: stale; run npx tsx scripts/combinatorics/generate.ts'
    );
    process.exit(1);
  }
  // This process already loaded the old definitions: run again with the new.
  writeFileSync(compiledFile, compiledSource);
  process.exit(
    spawnSync(
      process.execPath,
      [...process.execArgv, ...process.argv.slice(1)],
      {
        stdio: 'inherit',
      }
    ).status ?? 1
  );
}

const read = (file: string) =>
  JSON.parse(readFileSync(join(data, file), 'utf8'));

const ce = new ComputeEngine();
loadCombinatorics(ce);

const heads = new Map(
  COMBINATORICS_AREAS.flatMap((area) =>
    area.statistics.map((s) => [s.head, { area, statistic: s }] as const)
  )
);

// Example rows.
const exampleCounts: Record<string, number> = {};
for (const area of COMBINATORICS_AREAS) {
  const file = `examples/${area.name}.json`;
  const { entries } = read(file) as {
    entries: {
      id: string;
      head: string;
      input: unknown;
      expected?: unknown;
      unevaluated?: boolean;
    }[];
  };
  const ids = new Set<string>();
  for (const e of entries) {
    if (ids.has(e.id)) problems.push(`${file}: duplicate id ${e.id}`);
    ids.add(e.id);
    if (heads.get(e.head)?.area !== area)
      problems.push(
        `${file}: ${e.id}: head ${e.head} is not a statistic of ${area.name}`
      );
    if ((e.expected === undefined) === (e.unevaluated !== true))
      problems.push(
        `${file}: ${e.id}: exactly one of expected / unevaluated: true`
      );
  }
  exampleCounts[area.name] = entries.length;
}

// FindStat values: our value on each object, by the engine.
const parseObject = (key: string): number[] =>
  key === '[]' ? [] : key.slice(1, -1).split(',').map(Number);
const matches = [];
for (const { area, statistic } of heads.values()) {
  if (statistic.findstat === undefined) continue;
  const file = `findstat/values/${statistic.findstat}.json`;
  const fixture = read(file) as {
    collection: string;
    through: number;
    values: Record<string, number>;
  };
  if (fixture.collection !== area.domain.collection)
    problems.push(
      `${file}: collection ${fixture.collection} is not ${area.domain.collection}`
    );
  let compared = 0;
  for (const [key, value] of Object.entries(fixture.values)) {
    compared++;
    if (!evaluateValues) continue;
    const ours = ce
      .box([statistic.head, ['List', ...parseObject(key)]])
      .evaluate().json;
    if (ours !== value)
      problems.push(
        `${file}: ${statistic.head}(${key}) = ${JSON.stringify(ours)}, FindStat has ${value}`
      );
  }
  matches.push({
    head: statistic.head,
    area: area.name,
    domain: area.domain.type,
    collection: area.domain.collection,
    findstat: statistic.findstat,
    through: fixture.through,
    valuesCompared: compared,
  });
}

const json = (x: unknown) => JSON.stringify(x, null, 2) + '\n';
const generated: Record<string, string> = {
  'findstat/matches.json': json({
    source: 'https://www.findstat.org',
    credit:
      "Identifiers and our own value-match records. FindStat's values are mathematical facts, credited to FindStat (https://www.findstat.org).",
    matches,
  }),
  'MANIFEST.json': json({
    schema: 1,
    generator: 'scripts/combinatorics/generate.ts',
    areas: Object.fromEntries(
      COMBINATORICS_AREAS.map((a) => [
        a.name,
        {
          statistics: a.statistics.length,
          findstat: a.statistics.filter((s) => s.findstat !== undefined).length,
          examples: exampleCounts[a.name],
        },
      ])
    ),
    findstatMatches: matches.length,
  }),
};

for (const [file, text] of Object.entries(generated)) {
  const target = join(data, file);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== text)
      problems.push(
        `${file}: stale; run npx tsx scripts/combinatorics/generate.ts`
      );
  } else writeFileSync(target, text);
}

if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}
console.log(
  check ? 'data/combinatorics is fresh' : 'data/combinatorics written'
);
